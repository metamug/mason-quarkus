// Writes MqCompiledScripts.java: a ScriptLoader that calls the constructor of each script compiled from <dir>/*.kts.
// A script class is named after the file with a capital first letter (hashpw.kts -> Hashpw), in the default package.
import fs from 'node:fs';
import path from 'node:path';
const dir = process.argv[2];
const out = process.argv[3];
const names = fs.readdirSync(dir).filter((f) => f.endsWith('.kts')).map((f) => f.slice(0, -4)).sort();
const bad = names.filter((n) => !/^[A-Za-z_][A-Za-z0-9_]*$/.test(n));
if (bad.length) {
  console.error('script names must be identifiers (the name becomes a class name): ' + bad.join(', '));
  process.exit(1);
}
const cls = (n) => n[0].toUpperCase() + n.slice(1);
const has = names.map((n) => `            case "${n}": return true;`).join('\n');
const run = names.map((n) => `            case "${n}": new ${cls(n)}(p, s, r, q); return;`).join('\n');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, `import io.mq.script.Params;
import io.mq.script.RequestInfo;
import io.mq.script.Response;
import io.mq.script.ScriptLoader;
import io.mq.script.Steps;

/** generated by tools/mq-compile-scripts: the scripts compiled ahead of time; calling a script's constructor runs its body */
public final class MqCompiledScripts implements ScriptLoader {

    @Override
    public boolean has(String name) {
        switch (name) {
${has}
            default: return false;
        }
    }

    @Override
    public void run(String name, Params p, Steps s, Response r, RequestInfo q) {
        switch (name) {
${run}
            default: throw new IllegalArgumentException("no compiled script '" + name + "'");
        }
    }
}
`);
console.log('compiled scripts: ' + names.join(', '));
